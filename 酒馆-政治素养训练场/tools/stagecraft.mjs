/**
 * stagecraft.mjs — 演出规则与对话示例。三个转换器共用。
 *
 * 为什么单独抽出来：这是酒馆生态里的一个标准问题——模型拿到「处境 + 设定」之后，
 * 默认会写成旁白与心理描写，**没有人开口说话**，用户面对一堵背景墙无从接话。
 *
 * 标准做法有三样，缺一不可：
 *   1) 演出规则常驻条目：每轮强制在场人物开口、留话头；
 *   2) post_history_instructions 里再写一遍：那是每轮都在最后的位置；
 *   3) mes_example 对话示例：教模型**回合结构**——谁说话、怎么接。
 *
 * 规则要落在「每一轮」上，不能只写在开场白里；开场白是角色视角的处境，
 * 不该承担教模型怎么演的任务。
 */

/** 演出规则。三个转换器写入常驻世界书条目与 post_history_instructions。 */
export const STAGECRAFT = `# 演出规则（每一轮都要遵守）

**每一轮都必须有在场的人开口说话、并且做出动作。** 只有环境、回忆与心理描写的回复不合格。

- 以**对话与动作**为主体，环境与心理各不超过一两句。
- 至少让一个在场人物**主动**说一句或做一件事——不要让用户去猜谁在场、谁该答话。
- **收尾必须留一个用户可以直接接的话头**：一句问话、一个等待、一个明确的动作，都行。
  不要用静态陈述（例如「材料月底前要报」）收尾——那种结尾没有人可以回应。
- 不要替用户说话，不要替用户做决定，不要写用户的心理活动。
- 篇幅 2~4 段，宁短勿长。
- 不要把设定集里的内容直接倒出来讲；让它在对话与动作里显形。

# 开场结构

第一轮的开场分两段，**顺序不能颠倒**：

1. **活场景**——一个在场人物正在做事或说话，结尾是**他对用户提出的一个具体问题、或一个明确的等待**。
   用户读完这一段应当知道：现在谁在跟我说话、他在等我说什么。
2. **背景说明**——紧接着给出中立的事实交代，**只写三样**：
   - **派系**：有哪几方，各自的位置与手里的东西。
   - **现状**：此刻的形势，以及已经发生过的事。
   - **考量**：需要权衡的问题有哪些。

**背景说明不得有引导倾向。** 不给建议、不提示解法、不评价各方的利弊、不暗示哪条路更好，
不写「你应该……」「幸好……」「危险的是……」这类判断。**只说明现状，让用户自己判断。**`

/**
 * 生成一段对话示例。
 *
 * mes_example 的作用是示范**回合结构**，不是示范剧情：用户怎么发起、角色怎么回、
 * 回的时候带不带动作、结尾留不留话头。所以示例用本卡的真实人物名，内容取中性场景，
 * 不预设本卡的具体走向。
 *
 * @param {{name: string, seat?: string, note?: string}[]} cast 在场人物（取前两个）
 * @param {string} who 用户在那个位置上是什么身份（写进示例的一句说明）
 */
export function exampleDialogue(cast, who) {
  const a = cast[0]?.name ?? '对方'
  const b = cast[1]?.name
  const lines = [
    `<START>`,
    `{{user}}: 我直接问${a}，这件事到底是谁定的。`,
    `{{char}}: ${a}手上的动作停了一下，没有立刻回答。`,
    `「你问这个做什么？」${a}说，「定了就是定了。」`,
    b ? `${b}在旁边没说话，只是把杯子往桌角挪了半寸——这个动作${a}看见了。` : '',
    `${a}把话头转回来：「你先说说，你打算怎么办。」`,
    `<START>`,
    `{{user}}: 我不说话，就坐在那里等。`,
    `{{char}}: ${a}看了我一会儿，先开了口：「行，你不说，我替你说。」`,
    `「你要的是那件事有个说法。」${a}把纸推过来半寸，「那你得先让我知道，你手上有什么。」`,
    b ? `${b}这时候插了一句：「${a}，这话说得早了。」` : '',
    `屋里安静了两秒。${a}没有收回那句话。`,
  ]
  return lines.filter((line) => line !== '').join('\n')
}
